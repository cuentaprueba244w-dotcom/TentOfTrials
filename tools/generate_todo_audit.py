#!/usr/bin/env python3
"""Generate TODO_AUDIT.md with repository-wide technical debt tracking."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_FILE = ROOT / "TODO_AUDIT.md"

SCAN_EXTENSIONS = {".py", ".rs", ".ts", ".tsx", ".js", ".jsx", ".go", ".java",
    ".c", ".h", ".cpp", ".hpp", ".rb", ".lua", ".hs", ".sh",
    ".yml", ".yaml", ".md", ".css", ".scss", ".sql", ".pl", ".pm"}

SKIP_DIRS = {".git", "node_modules", "target", "dist", "build", ".venv", "__pycache__", "diagnostic"}


def find_todos():
    todos = []
    pattern = re.compile(r"TODO", re.IGNORECASE)
    for path in ROOT.rglob("*"):
        if not path.is_file(): continue
        if path.suffix.lower() not in SCAN_EXTENSIONS: continue
        parts = set(path.relative_to(ROOT).parts)
        if parts & SKIP_DIRS: continue
        if path == OUTPUT_FILE: continue
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").split("\n")
        except Exception: continue
        for line_num, line in enumerate(lines, 1):
            if pattern.search(line):
                match = pattern.search(line)
                desc = line[match.end():].strip()
                desc = re.sub(r"^[:\-\s]+", "", desc)
                if len(desc) > 120: desc = desc[:117] + "..."
                rel = str(path.relative_to(ROOT)).replace("\\", "/")
                est = (line_num % 7) + 1
                todos.append({"filename": rel, "line_number": line_num,
                              "description": desc or "(no description)", "est_hours": est})
    return todos


def generate_report(todos):
    todos_sorted = sorted(todos, key=lambda x: (-x["est_hours"], x["filename"], x["line_number"]))
    total_hours = sum(t["est_hours"] for t in todos_sorted)
    lines = ["# TODO Audit Report", "", "Repository-wide technical debt tracking.", "",
             f"- **Total TODOs found:** {len(todos_sorted)}",
             f"- **Total estimated effort:** {total_hours} hours",
             f"- **Estimate formula:** `(line_number % 7) + 1` hours", "",
             "## Summary by Estimated Effort", ""]
    by_hours = {}
    for t in todos_sorted:
        by_hours.setdefault(t["est_hours"], []).append(t)
    lines.append("| Est. Hours | Count |")
    lines.append("|-----------:|------:|")
    for h in sorted(by_hours.keys(), reverse=True):
        lines.append(f"| {h}h | {len(by_hours[h])} |")
    lines += ["", "## All TODOs (sorted by estimated hours descending)", "",
              "| # | Est. Hours | File | Line | Description |",
              "|--:|-----------:|------|-----:|-------------|"]
    for i, t in enumerate(todos_sorted, 1):
        d = t["description"].replace("|", "\\|")
        lines.append(f"| {i} | {t['est_hours']}h | `{t['filename']}` | {t['line_number']} | {d} |")
    lines += ["", "---", "", "*Generated by `tools/generate_todo_audit.py`*"]
    return "\n".join(lines)


def main():
    print("Generating TODO Audit Report...")
    todos = find_todos()
    print(f"Found {len(todos)} TODOs")
    report = generate_report(todos)
    OUTPUT_FILE.write_text(report, encoding="utf-8")
    total = sum(t["est_hours"] for t in todos)
    print(f"Report written to TODO_AUDIT.md")
    print(f"Total estimated effort: {total} hours")
    return 0


if __name__ == "__main__":
    sys.exit(main())
